package filter;

import jakarta.servlet.Filter;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebFilter;
import jakarta.servlet.ServletRequest;
import jakarta.servlet.ServletResponse;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;

import java.io.IOException;

import java.io.IOException;
import java.util.logging.Logger;


@WebFilter("/message")
public class AuthenticationFilter implements Filter {

    private static final Logger logger =
            Logger.getLogger(AuthenticationFilter.class.getName());

    @Override
    public void doFilter(ServletRequest request,
                         ServletResponse response,
                         FilterChain chain)
            throws IOException, ServletException {

        HttpServletRequest req =
                (HttpServletRequest) request;

        HttpServletResponse resp =
                (HttpServletResponse) response;

        // 1. INCOMING REQUEST
        logger.info("========== REQUEST ENTERED FILTER ==========");
        logger.info("HTTP Method: " + req.getMethod());
        logger.info("Request URI: " + req.getRequestURI());
        logger.info("Remote Address: " + req.getRemoteAddr());

        HttpSession session = req.getSession(false);

        if (session == null ||
                session.getAttribute("username") == null) {

            logger.warning("Authentication Failed!");

            // 2. FILTER GENERATES RESPONSE
            resp.sendRedirect(
                    req.getContextPath() + "/login.jsp"
            );

            logger.info("Response generated by Filter");
            logger.info("Response Status: " + resp.getStatus());
            logger.info("Redirect Location: " +
                    resp.getHeader("Location"));

            return;
        }

        logger.info("Authentication Successful!");
        logger.info("Passing request to MessageServlet...");

        // 3. CONTINUE REQUEST PROCESSING
        chain.doFilter(request, response);

        // 4. RESPONSE RETURNS THROUGH FILTER
        logger.info("========== RESPONSE RETURNED TO FILTER ==========");
        logger.info("Response Status: " + resp.getStatus());
        logger.info("Request Completed: " + req.getRequestURI());
    }
}
